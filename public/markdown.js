import { Marked } from '/vendor/marked.js';
import DOMPurify from '/vendor/purify.js';
import katex from '/vendor/katex.js';

// Math is tokenized before Markdown can consume TeX backslashes or underscores.
// Marked owns Markdown escapes and code spans/fences; these tokens have no children.
function mathToken(src, block = false) {
  const opening = /^(\$\$|\\\[|\\\(|\$)/.exec(src)?.[0];
  if (!opening || (block && !['$$', '\\['].includes(opening))) return;
  const display = opening === '$$' || opening === '\\[';
  const closing = opening === '\\[' ? '\\]' : opening === '\\(' ? '\\)' : opening;
  if (opening === '$' && /\s|\$/.test(src[1] || ' ')) return;
  for (let i = opening.length; i < src.length; i++) {
    if (!display && src[i] === '\n') return;
    if (src.startsWith(closing, i)) {
      if (opening === '$' && (/\s/.test(src[i - 1]) || /\d/.test(src[i + 1] || ''))) continue;
      const end = i + closing.length;
      if (block && !/^(?:[ \t]*\n|[ \t]*$)/.test(src.slice(end))) return;
      return { type: block ? 'displayMath' : 'inlineMath', raw: src.slice(0, end), text: src.slice(opening.length, i), display };
    }
    // An escaped dollar or a doubled backslash cannot close a delimiter.
    if (src[i] === '\\') i++;
  }
}

export function cleanMarkdown(text) {
  const publicText = String(text || '').replace(/```relentless-(?:state|tune|accepted|question)\s*\n[\s\S]*?\n```/g, '').replace(/```relentless-(?:state|tune|accepted|question)[\s\S]*$/, '');
  const prefix = `RELENTLESSMATH${crypto.randomUUID().replaceAll('-', '')}X`, formulas = [];
  const placeholder = token => { const marker = `${prefix}${formulas.length}END`; formulas.push(token); return token.type === 'displayMath' ? `<p>${marker}</p>\n` : marker; };
  const parser = new Marked({ breaks: false, extensions: [
    { name: 'displayMath', level: 'block', start: src => src.search(/(?:^|\n)(?:\$\$|\\\[)/), tokenizer: src => mathToken(src, true), renderer: placeholder },
    { name: 'inlineMath', level: 'inline', start: src => src.search(/\$|\\[([]/), tokenizer(src) { if (!this.lexer.state.inRawBlock) return mathToken(src); }, renderer: placeholder }
  ] });
  // Keep the existing Markdown allowlist. User HTML never gains KaTeX's tags,
  // style attributes, classes, SVG, MathML, or an addressable placeholder element.
  const html = DOMPurify.sanitize(parser.parse(publicText), { ALLOWED_TAGS: ['p', 'br', 'strong', 'em', 'del', 'a', 'ul', 'ol', 'li', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'blockquote', 'pre', 'code', 'hr', 'table', 'thead', 'tbody', 'tr', 'th', 'td'], ALLOWED_ATTR: ['href', 'title', 'start'], ALLOW_DATA_ATTR: false });
  const template = document.createElement('template'); template.innerHTML = html;
  for (const a of template.content.querySelectorAll('a')) {
    const href = a.getAttribute('href') || '';
    if (!/^(https?:|mailto:|#)/i.test(href)) a.removeAttribute('href');
    a.target = '_blank'; a.rel = 'noopener noreferrer';
  }
  const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT), nodes = [];
  while (walker.nextNode()) if (walker.currentNode.textContent.includes(prefix)) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const output = document.createDocumentFragment(), pattern = new RegExp(`${prefix}(\\d+)END`, 'g');
    let start = 0;
    for (const match of node.textContent.matchAll(pattern)) {
      output.append(document.createTextNode(node.textContent.slice(start, match.index)));
      const formula = formulas[Number(match[1])], math = document.createElement('span');
      math.className = formula.display ? 'math-display' : 'math-inline';
      // The only richer DOM is generated by this pinned library, with no shared
      // macros or trusted URL/HTML commands. render() sets style properties via
      // the DOM API, so the existing style-src 'self' CSP stays unchanged.
      try {
        if (formula.text.length > 12000) throw new Error('Formula is too long to preview.');
        katex.render(formula.text, math, { displayMode: formula.display, throwOnError: true, trust: false, strict: 'error', maxSize: 20, maxExpand: 1000, macros: {}, output: 'htmlAndMathml' });
      } catch {
        // ParseError messages may contain raw TeX; retain only the exact source.
        math.className = 'math-source'; math.textContent = formula.raw;
        math.title = 'This formula could not be rendered. Its source is preserved.';
      }
      output.append(math); start = match.index + match[0].length;
    }
    output.append(document.createTextNode(node.textContent.slice(start))); node.replaceWith(output);
  }
  return template.content;
}
